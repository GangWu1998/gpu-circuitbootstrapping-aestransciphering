    template <typename RealType,
              unsigned int PolyDim,
              unsigned int FFTsPerBlock,
              unsigned int ElementsPerThread,
              unsigned int Arch>
        requires std::is_same_v<RealType, __half> || std::is_same_v<RealType, float> || std::is_same_v<RealType, double>
    cuFFTDxWrapper<RealType, PolyDim, FFTsPerBlock, ElementsPerThread, Arch>::cuFFTDxWrapper()
    {
        twist_table_ = util::make_cuda_auto_ptr<complex_t>(PolyDim / 2, cudaStreamPerThread);
        if constexpr (PolyDim == 1024)
        {
            cudaMemcpyAsync(twist_table_.get(), &twist_512_table, sizeof(twist_512_table),
                            cudaMemcpyHostToDevice, cudaStreamPerThread);
        }
        else if constexpr (PolyDim == 2048)
        {
            cudaMemcpyAsync(twist_table_.get(), &twist_1024_table, sizeof(twist_1024_table),
                            cudaMemcpyHostToDevice, cudaStreamPerThread);
        }
        else if constexpr (PolyDim == 4096)
        {
            cudaMemcpyAsync(twist_table_.get(), &twist_2048_table, sizeof(twist_2048_table),
                            cudaMemcpyHostToDevice, cudaStreamPerThread);
        }
        else
        {
            throw std::runtime_error("cuFFTDxWrapper: Unsupported PolyDim. Supported values are 1024, 2048, and 4096.");
        }
    }

    template <typename RealType,
              unsigned int PolyDim,
              unsigned int FFTsPerBlock,
              unsigned int ElementsPerThread,
              unsigned int Arch>
        requires std::is_same_v<RealType, __half> || std::is_same_v<RealType, float> || std::is_same_v<RealType, double>
    void cuFFTDxWrapper<RealType, PolyDim, FFTsPerBlock, ElementsPerThread, Arch>::i2c_forward(
        complex_t* out, const BasicInteger* in, const size_t batch_size, const cudaStream_t& stream)
    {
        const auto grid_dim = dim3(batch_size);
        constexpr dim3 block_dim = Forward_FFT::block_dim;
        constexpr size_t shared_bytes = Forward_FFT::shared_memory_size;

        forward_fft_kernel<Forward_FFT, BasicInteger, RealType>
            <<<grid_dim, block_dim, shared_bytes, stream>>>(out, in, twist_table_.get());
        CUDA_CHECK_AND_EXIT(cudaPeekAtLastError());
    }

    template <typename RealType,
              unsigned int PolyDim,
              unsigned int FFTsPerBlock,
              unsigned int ElementsPerThread,
              unsigned int Arch>
        requires std::is_same_v<RealType, __half> || std::is_same_v<RealType, float> || std::is_same_v<RealType, double>
    void cuFFTDxWrapper<RealType, PolyDim, FFTsPerBlock, ElementsPerThread, Arch>::c2i_inverse(
        BasicInteger* out, const complex_t* in, const BasicInteger Q, const size_t batch_size,
        const cudaStream_t& stream)
    {
        const auto grid_dim = dim3(batch_size);
        constexpr dim3 block_dim = Inverse_FFT::block_dim;
        constexpr size_t shared_bytes = Inverse_FFT::shared_memory_size;

        inverse_fft_kernel<Inverse_FFT, BasicInteger, RealType>
            <<<grid_dim, block_dim, shared_bytes, stream>>>(out, in, twist_table_.get(), static_cast<int64_t>(Q));
        CUDA_CHECK_AND_EXIT(cudaPeekAtLastError());
    }

    template <typename RealType,
              unsigned int PolyDim,
              unsigned int FFTsPerBlock,
              unsigned int ElementsPerThread,
              unsigned int Arch>
        requires std::is_same_v<RealType, __half> || std::is_same_v<RealType, float> || std::is_same_v<RealType, double>
    void cuFFTDxWrapper<RealType, PolyDim, FFTsPerBlock, ElementsPerThread, Arch>::multiply_and_accumulate(
        complex_t* acc, const complex_t* multiplicand, const complex_t* multiplier,
        const size_t batch_size, const cudaStream_t& stream)
    {
        const auto grid_dim = dim3(batch_size);
        constexpr dim3 block_dim = Inverse_FFT::block_dim;
        constexpr size_t shared_bytes = 0;

        complex_multiply_and_accumulate_kernel<Inverse_FFT, RealType>
            <<<grid_dim, block_dim, shared_bytes, stream>>>(acc, multiplicand, multiplier);
        CUDA_CHECK_AND_EXIT(cudaPeekAtLastError());
    }

