    template <typename ComplexType>
    __device__ __forceinline__ ComplexType cmul(const ComplexType& a,
                                                const ComplexType& b)
    {
        ComplexType r;
        r.real(fmaf(-a.imag(), b.imag(), a.real() * b.real())); // (a.x * b.x – a.y * b.y)
        r.imag(fmaf(a.real(), b.imag(), a.imag() * b.real())); // (a.x * b.y + a.y * b.x)
        return r;
    }

    template <class Forward_FFT, typename InputType, typename RealType, typename ComplexType = cuda::std::complex<
                  RealType>>
    __launch_bounds__(Forward_FFT::max_threads_per_block) __global__
    void forward_fft_kernel(ComplexType* output, const BasicInteger* input, const ComplexType* twist_table)
    {
        using real_t = RealType;
        using complex_t = ComplexType;

        // Local array for thread
        complex_t thread_data[Forward_FFT::storage_size];

        // ID of FFT in CUDA block, in range [0; FFTR2C::ffts_per_block)
        const unsigned int local_fft_id = threadIdx.y;

        // Load data from global memory to registers
        {
            // Calculate global offset of FFT batch
            unsigned int global_fft_id = blockIdx.x * Forward_FFT::ffts_per_block + local_fft_id;
            const unsigned int offset = 2 * Forward_FFT::input_length * global_fft_id;
            // Get stride, this shows how elements from batch should be split between threads
            const unsigned int stride = Forward_FFT::stride;
            unsigned int index = offset + threadIdx.x;
            for (unsigned int i = 0; i < Forward_FFT::input_ept; i++)
            {
                const size_t j = i * stride + threadIdx.x;
                if (j < Forward_FFT::input_length)
                {
                    // folding
                    thread_data[i] = cuda::std::complex(
                        static_cast<real_t>(input[index]),
                        static_cast<real_t>(input[index + Forward_FFT::input_length]));

                    // down-scaling
                    // constexpr double down_scale = 1.0 / 8192.0; // 2^-13
                    // thread_data[i] *= down_scale;

                    // twisting
                    thread_data[i] *= twist_table[j];

                    index += stride;
                }
            }
        }

        // Execute FFT
        extern __shared__ __align__(alignof(float4)) complex_t shared_mem[];
        Forward_FFT().execute(thread_data, shared_mem);

        // Save results
        {
            unsigned int global_fft_id = blockIdx.x * Forward_FFT::ffts_per_block + local_fft_id;
            const unsigned int offset = Forward_FFT::output_length * global_fft_id;
            const unsigned int stride = Forward_FFT::stride;
            unsigned int index = offset + threadIdx.x;

            for (int i = 0; i < Forward_FFT::output_ept; ++i)
            {
                size_t j = i * stride + threadIdx.x;
                if (j < Forward_FFT::output_length)
                {
                    output[index] = thread_data[i];
                    index += stride;
                }
            }
        }
    }

    template <class Inverse_FFT, typename OutputType, typename RealType, typename ComplexType = cuda::std::complex<
                  RealType>>
    __launch_bounds__(Inverse_FFT::max_threads_per_block) __global__
    void inverse_fft_kernel(BasicInteger* output, const ComplexType* input,
                            const ComplexType* twist_table, const int64_t Q)
    {
        using real_t = RealType;
        using complex_t = ComplexType;

        // Local array for thread
        complex_t thread_data[Inverse_FFT::storage_size];

        // ID of FFT in CUDA block, in range [0; FFTR2C::ffts_per_block)
        const unsigned int local_fft_id = threadIdx.y;

        // Load data from global memory to registers
        {
            // Calculate global offset of FFT batch
            unsigned int global_fft_id = blockIdx.x * Inverse_FFT::ffts_per_block + local_fft_id;
            const unsigned int offset = Inverse_FFT::input_length * global_fft_id;
            // Get stride, this shows how elements from batch should be split between threads
            const unsigned int stride = Inverse_FFT::stride;
            unsigned int index = offset + threadIdx.x;
            for (unsigned int i = 0; i < Inverse_FFT::input_ept; i++)
            {
                const size_t j = i * stride + threadIdx.x;
                if (j < Inverse_FFT::input_length)
                {
                    thread_data[i] = input[index];
                    index += stride;
                }
            }
        }

        // Execute FFT
        extern __shared__ __align__(alignof(float4)) complex_t shared_mem[];
        Inverse_FFT().execute(thread_data, shared_mem);

        // Save results
        unsigned int global_fft_id = blockIdx.x * Inverse_FFT::ffts_per_block + local_fft_id;
        const unsigned int offset = 2 * Inverse_FFT::output_length * global_fft_id;
        const unsigned int stride = Inverse_FFT::stride;
        unsigned int index = offset + threadIdx.x;

        for (int i = 0; i < Inverse_FFT::output_ept; ++i)
        {
            size_t j = i * stride + threadIdx.x;
            if (j < Inverse_FFT::output_length)
            {
                // Scale 1/N
                constexpr real_t inv_n = 1.0 / cufftdx::size_of<Inverse_FFT>::value;
                thread_data[i] *= inv_n;

                // untwisting
                thread_data[i] *= complex_t(twist_table[j].real(), -twist_table[j].imag());

                // up-scaling
                // constexpr double up_scale = 67108864.0; // 2^26
                // thread_data[i] *= up_scale;

                // mod reduce
                int64_t a = remainder(thread_data[i].real(), static_cast<real_t>(Q));
                int64_t b = remainder(thread_data[i].imag(), static_cast<real_t>(Q));
                if (a < 0) a += Q; // Ensure non-negative
                if (b < 0) b += Q; // Ensure non-negative

                // unfolding
                output[index] = static_cast<uint64_t>(a);
                output[index + Inverse_FFT::output_length] = static_cast<uint64_t>(b);

                index += stride;
            }
        }
    }

    template <class Inverse_FFT, typename RealType, typename ComplexType = cuda::std::complex<RealType>>
    __launch_bounds__(Inverse_FFT::max_threads_per_block) __global__
    void complex_multiply_and_accumulate_kernel(ComplexType* acc,
                                                const ComplexType* multiplicand,
                                                const ComplexType* multiplier)
    {
        using real_t = RealType;
        using complex_t = ComplexType;

        // Local batch id of this FFT in CUDA block, in range [0; FFT::ffts_per_block)
        const unsigned int local_fft_id = threadIdx.y;

        // Calculate global offset of FFT batch
        unsigned int global_fft_id = blockIdx.x * Inverse_FFT::ffts_per_block + local_fft_id;
        const unsigned int offset = Inverse_FFT::input_length * global_fft_id;
        // Get stride, this shows how elements from batch should be split between threads
        const unsigned int stride = Inverse_FFT::stride;
        unsigned int index = offset + threadIdx.x;
        for (unsigned int i = 0; i < Inverse_FFT::input_ept; i++)
        {
            if ((i * stride + threadIdx.x) < Inverse_FFT::input_length)
            {
                const complex_t a = multiplicand[index];
                const complex_t b = multiplier[index];
                complex_t prod = a * b; // standard complex product
                acc[index] += prod;
                index += stride;
            }
        }
    }

